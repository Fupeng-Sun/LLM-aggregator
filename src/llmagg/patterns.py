"""Myopic investment without an aggregator in the full-coverage regime (Section 4.3 of the paper).

Proposition 4 (``prop:myopic_full_coverage_noagg_selector``) states the myopic marginal-revenue heuristic
phi^{X,my} of Eq. (``phiA_myopic_bangbang``) in closed form when the aggregator is absent and the market is fully
covered (regime B-A of Proposition 1(d)): with the gap ratio delta_b/delta_a, where delta_a = a_A - a_B and
delta_b = b_B - b_A,

    (i)   delta_b/delta_a <  min(a_A/b_A, a_B/b_B):            both providers invest in feature b,
    (ii)  a_Y/b_Y <= delta_b/delta_a < a_X/b_X:                 X invests in b and Y in a,
    (iii) delta_b/delta_a >= max(a_A/b_A, a_B/b_B):            both providers invest in feature a,

i.e., provider X invests its whole budget in feature a iff delta_b/delta_a >= a_X/b_X (ties go to feature a, as in
Eq. (``phiA_myopic_bangbang``)). The rule depends only on the state, not on p, w_X or rho_0. Iterated with the state
update of Eq. (``next_state``), it generates the competition paths that Theorem 4
(``thm:myopic_full_coverage_noagg_patterns``) classifies with the reversals of Definition 3 (Figure 10).
"""

import numpy as np


def invests_in_a(a_X: float, b_X: float, delta_a: float, delta_b: float) -> bool:
    """Proposition 4: provider X invests in feature a iff delta_b/delta_a >= a_X/b_X.

    The proposition assumes delta_a, delta_b > 0 and relabels the providers if both gaps are negative; relabeling
    leaves both the gap ratio and a_X/b_X unchanged, so the rule holds whenever delta_a delta_b > 0 (no dominance).
    """
    if delta_a * delta_b <= 0:
        raise ValueError("Proposition 4 requires delta_a delta_b > 0 (no provider dominates)")
    return delta_b / delta_a >= a_X / b_X


def myopic_shares(x: np.ndarray) -> tuple[float, float]:
    """Budget shares (lambda_A, lambda_B) in feature a under phi^{X,my} (1.0 = feature a, 0.0 = feature b).

    ``x = (a_A, b_A, a_B, b_B)``; the closed form of Proposition 4. The same convention as
    ``llmagg.market.myopic_lambda`` and ``classify``.
    """
    a_A, b_A, a_B, b_B = x
    delta_a, delta_b = a_A - a_B, b_B - b_A
    return float(invests_in_a(a_A, b_A, delta_a, delta_b)), float(invests_in_a(a_B, b_B, delta_a, delta_b))


def myopic_path(x0, c: float, delta_T: float, T: int) -> tuple[np.ndarray, np.ndarray]:
    """States x(0), ..., x(T) generated by the heuristic, and the budget shares in feature a in periods 0..T-1.

    In period t provider X plays phi^{X,my}(x(t), t) = (c/a_X, 0) if it invests in feature a and (0, c/b_X)
    otherwise (Eq. (``phiA_myopic_bangbang``), the budget a_X u_a + b_X u_b = c binding), and the state moves to
    x(t+1) = x(t) + Delta_T (u^A, u^B) (Eq. (``next_state``)). Only the per-period budget c Delta_T affects the path.
    Returns ``path`` of shape (T+1, 4) and ``lam`` of shape (T, 2), as in ``llmagg.dynamics.simulate``.
    """
    path = np.empty((T + 1, 4))
    lam = np.empty((T, 2))
    path[0] = x0
    for t in range(T):
        a_A, b_A, a_B, b_B = path[t]
        lam_A, lam_B = myopic_shares(path[t])
        u_A = (c / a_A, 0.0) if lam_A == 1.0 else (0.0, c / b_A)
        u_B = (c / a_B, 0.0) if lam_B == 1.0 else (0.0, c / b_B)
        path[t + 1] = (a_A + delta_T * u_A[0], b_A + delta_T * u_A[1], a_B + delta_T * u_B[0], b_B + delta_T * u_B[1])
        lam[t] = lam_A, lam_B
    return path, lam


def classify(path, lam, tol=0.5):
    """Reversal periods, switches, dominance, and the investment pattern along a path."""
    da = path[:, 0] - path[:, 2]
    db = path[:, 3] - path[:, 1]
    sa = np.sign(da)
    sb = np.sign(db)
    reversals = []
    switches = []
    dominance = None
    for t in range(1, len(path)):
        ra = sa[t] != sa[t - 1] or da[t] == 0
        rb = sb[t] != sb[t - 1] or db[t] == 0
        if ra or rb:
            reversals.append(t)
            if da[t] * db[t] <= 0:
                if dominance is None:
                    dominance = t
            elif ra and rb:
                switches.append(t)
    feat = []
    for lA, lB in lam:
        fa = "a" if lA > tol else ("b" if lA < 1 - tol else "s")
        fb = "a" if lB > tol else ("b" if lB < 1 - tol else "s")
        feat.append(fa + fb)
    # single-feature race: from some period on both invest in the same feature and no reversal afterwards
    Ts = None
    for t in range(len(feat)):
        if all(f in ("aa", "bb") and f == feat[t] for f in feat[t:]) and not any(r > t for r in reversals):
            Ts = t
            break
    # weak-feature investment: A's weak feature is b while da > 0 (a while da < 0); B's weak feature is a while db > 0
    weakA = all((f[0] == "b") == (da[t] > 0) for t, f in enumerate(feat) if f[0] != "s")
    weakB = all((f[1] == "a") == (db[t] > 0) for t, f in enumerate(feat) if f[1] != "s")
    if dominance is not None:
        label = "dominance"
    elif Ts is not None and Ts < len(feat):
        label = f"race on {feat[Ts][0]} from t={Ts}"
    elif switches and weakA and weakB:
        label = "perpetual switching"
    elif not reversals and weakA and weakB:
        label = "catch-up (no reversal within horizon)"
    else:
        label = "other"
    return dict(
        reversals=reversals,
        switches=switches,
        dominance=dominance,
        race_start=Ts,
        features="".join(f[0] for f in feat) + "|" + "".join(f[1] for f in feat),
        label=label,
        da=da,
        db=db,
    )
